// Spec 20 in the browser: a full week with auto-resolve, a deployed Night Market variant that returns to the city, Continue after
// a reload (rule 22), district picking on the table (rule 25), and the phone layout.
import { expect, test, type Page } from '@playwright/test'
import { openStart, watchErrors } from './helpers'

async function newCampaign(page: Page): Promise<void> {
  await openStart(page)
  await page.evaluate(() => window.__px.setSpeed('instant'))
  await page.getByTestId('new-campaign').click()
  await expect(page.getByTestId('city-hud')).toBeVisible()
  await expect(page.getByTestId('week')).toHaveText('WEEK 01')
}

/** Entering the city briefs the first incident; this goes back to the incident list. */
async function toList(page: Page): Promise<void> {
  if (await page.getByTestId('brief-back').isVisible()) await page.getByTestId('brief-back').click()
  await expect(page.getByTestId('incidents')).toBeVisible()
}

test.setTimeout(420_000)

test('WEEK-4 / AUTO-1 a full week: brief, auto-resolve, after-action report, roster, end week', async ({ page }) => {
  const errs = watchErrors(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await newCampaign(page)
  expect(await page.evaluate(() => localStorage.getItem('px-campaign'))).not.toBeNull() // written before the first render
  await toList(page)
  const cards = page.getByTestId('incident-card')
  expect(await cards.count()).toBeGreaterThanOrEqual(2)
  await cards.first().click()
  await expect(page.getByTestId('brief')).toBeVisible()
  await expect(page.getByTestId('win-chance')).toContainText('% win')
  // squad change: drop one trooper, the odds follow the engine
  const before = await page.getByTestId('win-chance').textContent()
  await page.getByTestId('squad-pick').first().click()
  await expect(page.getByTestId('win-chance')).not.toHaveText(before ?? '')
  await page.getByTestId('squad-pick').first().click()
  await page.getByTestId('auto-resolve').click()
  await expect(page.getByTestId('aar')).toBeVisible()
  await expect(page.getByTestId('aar-outcome')).toHaveText(/INCIDENT (CLOSED|FAILED)|PARTIAL RESULT/)
  await expect(page.getByTestId('aar')).toContainText('auto-resolved')
  await page.getByTestId('aar-close').click()
  await page.getByTestId('open-roster').click()
  await expect(page.getByTestId('roster')).toBeVisible()
  expect(await page.getByTestId('roster-row').count()).toBe(6)
  await page.getByTestId('roster-close').click()
  await page.getByTestId('end-week').click()
  await expect(page.getByTestId('week')).toHaveText('WEEK 02')
  const c = await page.evaluate(() => window.__px.campaign())
  expect(c.week).toBe(2)
  expect(c.log.map((a: { type: string }) => a.type)).toEqual(['autoResolve', 'endWeek'])
  expect(errs).toEqual([])
})

test('OPS-1 / OPS-5 / OPS-6 a deployed Night Market raid plays on the board and returns to the city with its report', async ({ page }) => {
  const errs = watchErrors(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await newCampaign(page)
  const raid = await page.evaluate(() => window.__px.campaign().incidents.find((i: any) => i.kind === 'raid').id)
  await toList(page)
  await page.locator(`[data-incident="${raid}"]`).click()
  await expect(page.getByTestId('brief')).toContainText('RAID')
  await page.getByTestId('deploy').click()
  await expect(page.getByTestId('hud')).toBeVisible()
  expect(await page.evaluate(() => window.__px.mode())).toBe('campaign')
  const st = await page.evaluate(() => window.__px.state())
  expect(st.setup.objective).toBe('raid')
  expect(st.raid.seized).toBe(false)
  expect(st.tuning.alarm.t1).toBe(3) // spire: corporate alarms
  await expect(page.getByTestId('objective')).toContainText('RAID')
  expect(await page.evaluate(() => localStorage.getItem('px-campaign-mission'))).not.toBeNull()
  expect(await page.evaluate(() => localStorage.getItem('px-save'))).toBeNull() // the single-operation slot is untouched
  const res = await page.evaluate(() => window.__px.autoplay(6000))
  expect(res.screen).toBe('end')
  await expect(page.getByTestId('end-screen')).toBeVisible()
  // the result is already in the campaign (reported as the mission ended)
  const c = await page.evaluate(() => window.__px.campaign())
  expect(c.phase).toBe('week')
  expect(c.report.mode).toBe('deployed')
  await page.getByTestId('return-city').click()
  await expect(page.getByTestId('city-hud')).toBeVisible()
  await expect(page.getByTestId('aar')).toBeVisible()
  await expect(page.getByTestId('aar')).toContainText('deployed')
  expect(await page.evaluate(() => localStorage.getItem('px-campaign-mission'))).toBeNull()
  await page.getByTestId('aar-close').click()
  await page.getByTestId('end-week').click()
  await expect(page.getByTestId('week')).toHaveText('WEEK 02')
  expect(errs).toEqual([])
})

test('CMP-9 / rule 22 Continue campaign after a reload, in the city and in a deployed mission', async ({ page }) => {
  const errs = watchErrors(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await newCampaign(page)
  await toList(page)
  await page.getByTestId('incident-card').first().click()
  await page.getByTestId('auto-resolve').click()
  await page.getByTestId('aar-close').click()
  await page.getByTestId('end-week').click()
  await expect(page.getByTestId('week')).toHaveText('WEEK 02')
  const saved = await page.evaluate(() => window.__px.campaign())
  await page.reload()
  await expect(page.getByTestId('campaign-continue-card')).toContainText('Week 2')
  await expect(page.getByTestId('continue-campaign')).toBeEnabled({ timeout: 60_000 })
  await page.getByTestId('continue-campaign').click()
  await expect(page.getByTestId('city-hud')).toBeVisible()
  expect(await page.evaluate(() => window.__px.campaign())).toEqual(saved)
  // deployed: a reload reopens the same mission on the board
  await page.evaluate(() => window.__px.setSpeed('instant'))
  await toList(page)
  await page.getByTestId('incident-card').first().click()
  await page.getByTestId('deploy').click()
  await expect(page.getByTestId('hud')).toBeVisible()
  await page.evaluate(() => window.__px.randomStep(1, 0))
  const mission = await page.evaluate(() => ({ seed: window.__px.state().setup.seed, actions: window.__px.state().log.length }))
  expect(mission.actions).toBeGreaterThan(0)
  await page.reload()
  await expect(page.getByTestId('campaign-continue-card')).toContainText('squad deployed')
  await expect(page.getByTestId('continue-campaign')).toBeEnabled({ timeout: 60_000 })
  await page.getByTestId('continue-campaign').click()
  await expect(page.getByTestId('hud')).toBeVisible()
  expect(await page.evaluate(() => ({ seed: window.__px.state().setup.seed, actions: window.__px.state().log.length }))).toEqual(mission)
  // withdraw: counts as lost, back to the city with the report
  await page.getByTestId('withdraw').click()
  await page.getByTestId('confirm-withdraw').click()
  await expect(page.getByTestId('aar')).toBeVisible()
  await expect(page.getByTestId('aar-outcome')).toHaveText('INCIDENT FAILED')
  // a corrupt save says why and offers to discard
  await page.evaluate(() => localStorage.setItem('px-campaign', '{"v":9}'))
  await page.reload()
  await expect(page.getByTestId('campaign-bad-save')).toContainText('unknown campaign save version')
  await page.getByTestId('discard-campaign').click()
  await page.getByTestId('confirm-discard-campaign').click()
  await expect(page.getByTestId('campaign-bad-save')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('px-campaign'))).toBeNull()
  expect(errs).toEqual([])
})

test('rule 25 tapping a district plate on the holo-table selects its incident', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await newCampaign(page)
  const target = await page.evaluate(() => {
    const c = window.__px.campaign()
    const i = c.incidents.find((x: any) => x.result === null && x.id !== window.__px.cincident())
    const k = c.districts.findIndex((d: any) => d.id === i.district)
    return { id: i.id, k }
  })
  await page.getByTestId('brief-back').click()
  await page.waitForTimeout(300)
  const p = await page.evaluate((k) => window.__px.districtToScreen(k), target.k)
  expect(p).not.toBeNull()
  // tap above the plate centre (on the skyline), where no HUD panel sits
  await page.mouse.click(p!.x, p!.y - 6)
  await expect.poll(() => page.evaluate(() => window.__px.cincident())).toBe(target.id)
  await expect(page.getByTestId('brief')).toBeVisible()
})

test('phone 390x844: the city, brief and roster fit without sideways scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await newCampaign(page)
  const fits = async (): Promise<boolean> => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
  expect(await fits()).toBe(true)
  for (const id of ['week', 'takeover', 'end-week', 'deploy', 'auto-resolve']) await expect(page.getByTestId(id)).toBeInViewport()
  await page.getByTestId('brief-back').click()
  await expect(page.getByTestId('incident-card').first()).toBeInViewport()
  await page.getByTestId('open-roster').click()
  await expect(page.getByTestId('roster-close')).toBeInViewport()
  expect(await fits()).toBe(true)
  await page.getByTestId('roster-close').click()
  expect(await page.evaluate(() => getComputedStyle(document.body).userSelect)).toBe('none')
})
